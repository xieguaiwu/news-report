// Package s2t 提供简体↔繁体中文双向转换，用于搜索时的简繁一致性匹配。
package s2t

import "strings"

// ToSimplified 将繁体中文转换为简体。未知字符原样保留。
func ToSimplified(s string) string {
	var sb strings.Builder
	for _, r := range s {
		if v, ok := t2s[r]; ok {
			sb.WriteRune(v)
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// ToTraditional 将简体中文转换为繁体。未知字符原样保留。
func ToTraditional(s string) string {
	var sb strings.Builder
	for _, r := range s {
		if v, ok := s2t[r]; ok {
			sb.WriteRune(v)
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// Normalize 将文本统一转换为简体，消除简繁差异。
func Normalize(s string) string { return ToSimplified(s) }

